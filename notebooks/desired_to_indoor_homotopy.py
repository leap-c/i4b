@app.cell
def _(
    DEPTH,
    FUTURE,
    HORIZON,
    PAST,
    causal_mask,
    gd_alpha_ui,
    gd_button,
    gd_iters_ui,
    np,
    target,
    train_slice,
    windows_future,
    windows_past,
):
    if gd_button.value:
        import time as _t

        _t0 = _t.time()
        _n = train_slice.stop - train_slice.start
        _g = np.ones(_n)
        _sc = 1 / (_g.sum() * HORIZON)
        _phi = {
            "Future": {
                _v: np.zeros((HORIZON, DEPTH + HORIZON)) for _v in FUTURE
            },
            "Past": {_v: np.zeros((HORIZON, DEPTH + 1)) for _v in PAST},
        }
        _alpha = 10.0 ** gd_alpha_ui.value
        losses_gd = []
        _prev = np.inf
        for _it in range(int(gd_iters_ui.value)):
            _pred = sum(
                np.einsum(
                    "hw,nw->nh",
                    _phi["Future"][_v],
                    windows_future[_v][train_slice],
                )
                for _v in FUTURE
            )
            _pred += sum(
                np.einsum(
                    "hw,nw->nh", _phi["Past"][_v], windows_past[_v][train_slice]
                )
                for _v in PAST
            )
            _err = _pred - target[train_slice]
            _loss = float(0.5 * (_g[:, None] * _err**2).sum() * _sc)
            losses_gd.append(_loss)
            if _loss > _prev:
                _alpha *= 0.5
            _prev = _loss
            for _v in FUTURE:
                _phi["Future"][_v] -= (
                    _alpha
                    * np.einsum(
                        "nh,n,nw->hw", _err, _g, windows_future[_v][train_slice]
                    )
                    * _sc
                )
                _phi["Future"][_v] *= causal_mask
            for _v in PAST:
                _phi["Past"][_v] -= (
                    _alpha
                    * np.einsum(
                        "nh,n,nw->hw", _err, _g, windows_past[_v][train_slice]
                    )
                    * _sc
                )
        _sec = _t.time() - _t0
        phi_gd = _phi
        gd_status = f"finished in {_sec:.0f} s"
    else:
        phi_gd, losses_gd, gd_status = None, [], "not run"
    return gd_status, losses_gd, phi_gd


