@app.cell
def _(
    FUTURE,
    HORIZON,
    PAST,
    causal_mask,
    np,
    phi_l2,
    qr_button,
    qr_iters_ui,
    target,
    tau_ui,
    train_slice,
    windows_future,
    windows_past,
):
    def _train_quantile(tau, iters, alpha0=1e-3):
        _phi = {
            "Future": {_v: phi_l2["Future"][_v].copy() for _v in FUTURE},
            "Past": {_v: phi_l2["Past"][_v].copy() for _v in PAST},
        }
        _n = train_slice.stop - train_slice.start
        _g = np.ones(_n)
        _sc = 1 / (_g.sum() * HORIZON)
        _target_w = (1.0 - tau, tau)
        _w = [0.2, 0.8] if tau > 0.5 else [0.8, 0.2]
        _logs = []
        _weights = [tuple(_w)]
        _alpha = alpha0
        _prev = np.inf
        for _it in range(iters):
            _pred = sum(
                np.einsum(
                    "hw,nw->nh",
                    _phi["Future"][_v],
                    windows_future[_v][train_slice],
                )
                for _v in FUTURE
            )
            _pred += sum(
                np.einsum(
                    "hw,nw->nh", _phi["Past"][_v], windows_past[_v][train_slice]
                )
                for _v in PAST
            )
            _err = _pred - target[train_slice]
            _loss = float(
                (_g[:, None] * (_w[0] * _err * (_err > 0)
                                - _w[1] * _err * (_err < 0))).sum() * _sc
            )
            _logs.append(_loss)
            if _loss > _prev:
                _alpha *= 0.5
            _prev = _loss
            _signs = _w[0] * (_err > 0) - _w[1] * (_err < 0)
            for _v in FUTURE:
                _phi["Future"][_v] -= (
                    _alpha
                    * np.einsum(
                        "nh,n,nw->hw", _signs, _g, windows_future[_v][train_slice]
                    )
                    * _sc
                )
                _phi["Future"][_v] *= causal_mask
            for _v in PAST:
                _phi["Past"][_v] -= (
                    _alpha
                    * np.einsum(
                        "nh,n,nw->hw", _signs, _g, windows_past[_v][train_slice]
                    )
                    * _sc
                )
            if _it % 20 == 19 and (
                abs(_w[0] - _target_w[0]) + abs(_w[1] - _target_w[1]) > 2e-3
            ):
                _w[0] = 0.5 * _w[0] + 0.5 * _target_w[0]
                _w[1] = 0.5 * _w[1] + 0.5 * _target_w[1]
                _weights.append(tuple(_w))
        return _phi, _logs, _weights

    if qr_button.value:
        import time as _t

        _tau_hi = float(tau_ui.value)
        _iters = int(qr_iters_ui.value)
        _t0 = _t.time()
        phi_lo, qr_log_lo, qr_w_lo = _train_quantile(1.0 - _tau_hi, _iters)
        phi_hi, qr_log_hi, qr_w_hi = _train_quantile(_tau_hi, _iters)
        qr_status = f"finished in {_t.time() - _t0:.0f} s"
    else:
        phi_lo = phi_hi = None
        qr_log_lo = qr_log_hi = qr_w_lo = qr_w_hi = []
        qr_status = "not run"
    return phi_hi, phi_lo, qr_log_hi, qr_log_lo, qr_status, qr_w_hi, qr_w_lo


