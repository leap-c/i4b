@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## 3. Exact causality-masked L2 solution

    Per lead $h$ the quadratic loss is minimized in closed form

    $$\theta_h^\star = (A_h^\top A_h)^{-1} A_h^\top y_h,\qquad
    A_h = \big[\,U_{\mathrm{fut}}[:, \mathrm{causal}(h)]\;\; U_{\mathrm{past}}\,\big],$$

    row-by-row over the training windows. This runs in a few seconds and gives
    the optimum that the iterative schemes below should approach.
    """)
    return


@app.cell
def _(
    DEPTH,
    FUTURE,
    HORIZON,
    PAST,
    np,
    target,
    train_slice,
    x_future_concat,
    x_past_concat,
):
    import time as _time

    _fw = DEPTH + HORIZON
    _pw = DEPTH + 1
    _t0 = _time.time()
    phi_l2 = {
        "Future": {_v: np.zeros((HORIZON, _fw)) for _v in FUTURE},
        "Past": {_v: np.zeros((HORIZON, _pw)) for _v in PAST},
    }
    for _i in range(HORIZON):
        _width = _i + DEPTH
        _cols = np.concatenate(
            [_q * _fw + np.arange(_width) for _q in range(len(FUTURE))]
        )
        _A = np.concatenate(
            [x_future_concat[train_slice, _cols], x_past_concat[train_slice]],
            axis=1,
        )
        _coef, _, _, _ = np.linalg.lstsq(_A, target[train_slice, _i], rcond=None)
        _off = 0
        for _q, _v in enumerate(FUTURE):
            phi_l2["Future"][_v][_i, :_width] = _coef[_off : _off + _width]
            _off += _width
        _off = len(FUTURE) * _width
        for _q, _v in enumerate(PAST):
            phi_l2["Past"][_v][_i] = _coef[_off + _q * _pw : _off + (_q + 1) * _pw]
    l2_solve_seconds = _time.time() - _t0
    return l2_solve_seconds, phi_l2


@app.cell
def _(FUTURE, PAST, np, windows_future, windows_past):
    def predict(phi, sel):
        _p = sum(
            np.einsum("hw,nw->nh", phi["Future"][_v], windows_future[_v][sel])
            for _v in FUTURE
        )
        _p += sum(
            np.einsum("hw,nw->nh", phi["Past"][_v], windows_past[_v][sel])
            for _v in PAST
        )
        return _p

    return (predict,)


