@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## Model and loss

    Sampling step $\Delta t = 15$ min, memory depth $D$ (6 h) and prediction
    horizon $H$ (24 h). At each prediction origin $k$ the model predicts the
    **deviation** of the indoor temperature from its current value:

    $$\hat{y}_{k,h} \;=\; \widehat{T}_{in}[k+h] - T_{in}[k]
    \;=\; \sum_{f \in \mathcal{F}} \phi_{f,h}^\top\, u_f[k {-} D : k {+} H]
    \;+\; \sum_{p \in \mathcal{P}} \phi_{p,h}^\top\, x_p[k {-} D : k],$$

    for leads $h = 1,\dots,H$, future inputs
    $\mathcal{F} = \{$Outdoor, Desired$\}$ with kernels
    $\Phi_f \in \mathbb{R}^{H \times (D+H)}$, and past inputs
    $\mathcal{P} = \{$Indoor, Supply, Return$\}$ with kernels
    $\Phi_p \in \mathbb{R}^{H \times (D+1)}$.

    **Causality.** At lead $h$ only information available up to $k+h-1$ may be
    used, so future kernels are projected onto the mask

    $$M_{h,j} = \mathbb{1}\{j \le h + D - 1\}, \qquad \Phi_f \leftarrow \Phi_f \odot M.$$

    **Loss.** With per-window error $e_{k,h} = \hat{y}_{k,h} - y_{k,h}$,
    forgetting factor $\gamma$ per day of age, and weights $(w_+, w_-)$,

    $$J_{\mathrm{QR}} = \frac{1}{H\sum_k \gamma^{\tau_k}} \sum_{k,h}
    \gamma^{\tau_k}\big( w_+\, e_{k,h}^+ + w_-\,e_{k,h}^- \big),
    \qquad e^+ = \max(e,0),\; e^-=\max(-e,0),$$

    $$J_{\mathrm{L2}} = \frac{1}{H\sum_k \gamma^{\tau_k}}\sum_{k,h}
    \gamma^{\tau_k}\, \tfrac{1}{2} e_{k,h}^2,$$

    $$J = (1-\lambda)\, J_{\mathrm{QR}} + \lambda\, J_{\mathrm{L2}},
    \qquad \lambda \in [0,1].$$

    The pinball loss with $(w_+,w_-) = (1-\tau,\tau)$ is minimized by the
    $\tau$-quantile of the target distribution, which gives prediction bands.

    **Exact L2 solution.** For $\lambda = 1$ and uniform $\gamma$, the optimum
    per lead $h$ is a least-squares problem over the causally allowed columns,
    solved with the normal equations as a reference for the iterative schemes.

    **Homotopy (QR).** The asymmetric absolute loss has a kink at zero; the
    weights are annealed from a warm start toward the targets,

    $$\omega_\pm^{(t+1)} = \tfrac{1}{2}\,\omega_\pm^{(t)} + \tfrac{1}{2}\,w_\pm^{*},$$

    until $\lvert \omega_+ - w_+^{*} \rvert + \lvert \omega_- - w_-^{*} \rvert
    < 2\cdot10^{-3}$, as in the reference script.
    """)
    return


